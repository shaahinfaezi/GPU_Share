"""Generate a per-file Persian inventory from the exact handoff manifests."""
from pathlib import Path
import json
import yaml
import build_pools

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]


def main():
    build_pools.main()
    rows = json.loads((HERE / 'sources.json').read_text(encoding='utf-8'))
    text = ['# شرح تک‌تک پیکربندی‌ها', '',
            'مقادیر زیر مستقیماً از فایل اصلی خوانده شده‌اند. سه حالت یک خانواده، جایگزین یکدیگرند؛ '
            'اعمال هم‌زمان همه پوشه‌ها به‌دلیل نام‌های مشترک صحیح نیست. برای حالت اختصاصی فقط یک خدمت '
            'مقیم باشد. پیکربندی اشتراکی هر خانواده شامل دو خدمت است.', '',
            'دستورها و نام کلیدها برای جلوگیری از تغییر معنای اجرایی، به شکل اصلی حفظ شده‌اند. '
            'نام مدل و تصویر نیز شناسه فنی هستند و ترجمه نمی‌شوند.', '']
    for row in rows:
        if not row['file'].startswith('configurations/'):
            continue
        d = yaml.safe_load((REPO / row['repo_source']).read_text(encoding='utf-8'))
        spec = d['spec']; c = spec['template']['containers'][0]
        text += ['## ' + row['file'], '',
                 'این فایل خدمت «' + d['metadata']['name'] + '» را برای مدل «' + spec['model']['name'] +
                 '» تعریف می‌کند. منشأ: `' + row['source'] + '`. حالت اجرا و سناریو در نام پوشه مشخص است.', '',
                 'مسیر مدل، تعداد نسخه و تصویر:', '', '```yaml',
                 yaml.safe_dump({'model': spec['model'], 'replicas': spec.get('replicas', 1), 'image': c['image']},sort_keys=False).rstrip(),
                 '```', '',
                 'آرگومان‌های زیر به زمان اجرای خدمت فرستاده می‌شوند. طول زمینه و تعداد دنباله، ظرفیت '
                 'زمینه و هم‌زمانی را محدود می‌کنند؛ درجه‌های تفکیک، نحوه تقسیم مدل را تعیین می‌کنند. '
                 'گزینه بهره‌برداری حافظه و سهم حافظه HAMI دو مفهوم متفاوت‌اند؛ بدون بازآزمایی افزایش داده نشوند.',
                 '', '```yaml', yaml.safe_dump({'args': c.get('args', [])},sort_keys=False).rstrip(), '```', '',
                 'درخواست‌ها مبنای پذیرش زمان‌بند و حدها سقف اعلام‌شده منابع هستند. تعداد دستگاه و سهم '
                 'حافظه گرافیکی با حافظه میزبان تفاوت دارند. متغیرهای محیطی حالت ترکیبی، اتصال مشتری '
                 'به خدمت MPS را تعیین می‌کنند؛ آن خدمت باید جداگانه فعال و بررسی شود.', '', '```yaml',
                 yaml.safe_dump({'resources': c['resources'], 'env': c.get('env', [])},sort_keys=False).rstrip(), '```', '',
                 'حجم‌ها و انتخابگر گره در فایل کامل باقی مانده‌اند. در انتقال به مقصد، مسیر مشترک MPS، '
                 'فضای نام، محل وزن‌ها و گره هدف را هماهنگ تغییر دهید. در پیکربندی تک‌گرهی، '
                 'تأیید جای‌گذاری واقعی روی دستگاه همچنان لازم است.', '']
    text += ['# نسخه‌های تطبیق‌یافته برای گروه گره و نمایش', '',
             'فایل‌های زیر تنظیم‌های زمان اجرای آزموده‌شده را با اتصال ذخیره‌سازی و انتخاب گروه گره ارائه می‌کنند. '
             'تفاوت عمدی حالت اختصاصی، سهم محاسبات ۱۰۰ برای پذیرش زمان‌بند است؛ '
             'این حالت با خط پایه تاریخی یکسان نیست. سایر آرگومان‌های زمان اجرا حفظ شده‌اند.', '']
    for item in json.loads((REPO / 'deployment/pool-provenance.json').read_text()):
        d = yaml.safe_load((REPO / 'deployment' / item['file']).read_text())
        text += ['## ' + item['file'], '', 'منبع اصلی: `' + item['source'] + '`.', '']
        if d['kind'] == 'LLMInferenceService':
            t = d['spec']['template']
            text += ['انتخابگر زیر محل اجرای پاد را محدود می‌کند. نام خدمت مستقل است و مسیر مدل '
                     'به حجم همان مقصد اشاره می‌کند. منابع و متغیرهای زمان اجرا در فایل کامل آمده‌اند.', '',
                     '```yaml', yaml.safe_dump({'name':d['metadata']['name'], 'model':d['spec']['model'],
                         'nodeSelector':t['nodeSelector'], 'resources':t['containers'][0]['resources']},
                         sort_keys=False).rstrip(), '```', '']
        elif d['kind'] == 'List':
            text += ['این فایل حجم محلی و ادعای آن را با نام و برچسب متناظر متصل می‌کند. '
                     'نام گره دارای SET باید پیش از اعمال جایگزین شود. مسیر /data2/hf-cache باید '
                     'حاوی وزن‌های واقعی باشد. سیاست حفظ داده Retain باقی مانده است. '
                     'این حجم به یک گره وابسته است و ذخیره‌سازی مشترک چندگرهی نیست.', '']
        elif d['kind'] == 'DaemonSet':
            text += ['سرپرست اصلی MPS با همان نام نگه داشته شده است؛ تنها انتخابگر گره به گروه '
                     'hami-mps و برچسب فعال‌سازی true محدود می‌شود. مسیر مشترک، شناسه کاربری، '
                     'دسترسی میزبان و فرمان‌های اصلی تغییر نکرده‌اند. پیش از تغییر حالت، مشتریان تخلیه شوند.', '']
        else:
            text += ['این نسخه همان هدف پایش موجود را به‌روزرسانی می‌کند و پیشوند pool را نیز '
                     'برای نام خدمت می‌پذیرد. برچسب نقش، نام گروه را نیز حفظ می‌کند تا نمودارها '
                     'گروه‌های هم‌زمان را با یکدیگر جمع نکنند. هدف دوم ساخته نمی‌شود. '
                     'درگاه ۸۰۰۰ و مسیر /metrics از پیکربندی اصلی حفظ شده‌اند.', '']
    text += ['## infrastructure/hami-values.yaml', '',
             'مقادیر نصب تازه نسخه ۲٫۹٫۰، انتخابگر گره مدیریت‌شده، انتخابگر فضای نام، دو سهم دستگاه، '
             'ضریب حافظه و هسته برابر یک، کلاس اجرای موجود nvidia و سیاست binpack را تعریف می‌کنند. '
             'فضای نام و گره‌ها باید برچسب gpu-share.io/managed=true داشته باشند. '
             'این فایل جایگزین خودکار مقادیر نصب موجود نیست؛ قبل از ارتقا تنظیم‌های قبلی حفظ و بازبینی شوند.', '']
    (HERE / 'CONFIGURATIONS_FA.md').write_text('\n'.join(text), encoding='utf-8')


if __name__ == '__main__':
    main()
